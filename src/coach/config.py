"""Runtime settings, read from environment variables (see .env.example)."""

from __future__ import annotations

import os
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path


def _flag(name: str, default: bool = False) -> bool:
    return os.getenv(name, str(default)).strip().lower() in {"1", "true", "yes", "on"}


@dataclass(frozen=True)
class Settings:
    llm_base_url: str
    llm_api_key: str
    llm_model: str
    llm_temperature: float
    llm_timeout: float
    llm_max_retries: int
    mock_llm: bool
    data_dir: Path
    max_followups: int
    default_lang: str
    default_address: str  # "informal" (du/tu) or "formal" (Sie/vous/Lei)
    feedback_mode: str  # "written" or "spoken"
    ack_mode: str  # "fixed" (neutral phrases) or "llm" (generated by the assess call)


def _find_data_dir() -> Path:
    env = os.getenv("COACH_DATA_DIR")
    here = Path(__file__).resolve()
    candidates = [Path(env)] if env else []
    candidates += [
        Path("/app/data"),
        here.parents[2] / "data",
    ]
    for c in candidates:
        if (c / "questions" / "questions.jsonl").exists():
            return c
    raise FileNotFoundError(f"No dataset directory found, tried: {candidates}")


def _llm_base_url() -> str:
    """LLM_BASE_URL, or for scripts on the host the Docker endpoint (the compose service `vllm` is localhost there)."""
    url = os.getenv("LLM_BASE_URL") or os.getenv("LLM_BASE_URL_DOCKER") or "http://localhost:8000/v1"
    return url.replace("://vllm:", "://localhost:")


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    return Settings(
        llm_base_url=_llm_base_url(),
        llm_api_key=os.getenv("LLM_API_KEY", "EMPTY"),
        llm_model=os.getenv("LLM_MODEL", "swiss-ai/Apertus-v1.5-8B"),
        llm_temperature=float(os.getenv("LLM_TEMPERATURE", "0.3")),
        llm_timeout=float(os.getenv("LLM_TIMEOUT", "300")),
        llm_max_retries=int(os.getenv("LLM_MAX_RETRIES", "3")),
        mock_llm=_flag("COACH_MOCK_LLM"),
        data_dir=_find_data_dir(),
        max_followups=int(os.getenv("COACH_MAX_FOLLOWUPS", "1")),
        default_lang=os.getenv("COACH_DEFAULT_LANG", "de"),
        default_address=os.getenv("COACH_ADDRESS", "informal"),
        feedback_mode=os.getenv("COACH_FEEDBACK_MODE", "written"),
        ack_mode=os.getenv("COACH_ACK_MODE", "fixed"),
    )
